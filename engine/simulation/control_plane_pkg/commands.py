@dataclass(frozen=True)
class TraitInjectionCommand(CommandBase):
    """Phase 5B: Inject trait alleles into genomes via ControlPlane.

    Payload fields are stored under the nested "trait_injection" key.

    Important
    ---------
    - apply_to_sim is intentionally a no-op.
      Runtime application is done at SafeBoundary-approved apply phases by scanning
      the ControlPlane event log.
    """

    trait_injection: Dict[str, Any]

    def payload_dict(self) -> Dict[str, Any]:
        ti = dict(self.trait_injection or {})

        # Embed cost model deterministically (derived from duration + apply_phase).
        try:
            ap = str(ti.get("apply_phase", "") or "")
            dur = normalize_duration_generations(ti)
            ti["cost_model_v1"] = trait_injection_cost_model(dur, ap)
        except Exception:
            pass

        return {
            "schema_version": self.schema_version,
            "command_type": "TraitInjectionCommand",
            "command_uuid": self.command_uuid,
            "target_generation": int(self.target_generation),
            "trait_injection": ti,
        }


def parse_command(obj: Dict[str, Any]) -> CommandBase:
    """Parse a command dict (from inbox json) into a CommandBase instance."""
    if not isinstance(obj, dict):
        raise TypeError("command must be a JSON object")
    ctype = str(obj.get("command_type", "") or "")
    schema_version = str(obj.get("schema_version", "") or "")
    command_uuid = str(obj.get("command_uuid", "") or "")
    if not command_uuid:
        # We avoid generating random UUIDs here to keep deterministic behavior for submitters.
        # Tooling can generate it. For convenience, we allow generation if absent.
        command_uuid = str(_uuid.uuid4())
    target_generation = int(obj.get("target_generation", 0))

    if ctype == "PressureUpdateCommand":
        updates = obj.get("updates", []) or []
        if not isinstance(updates, list):
            raise TypeError("updates must be a list")
        return PressureUpdateCommand(schema_version, command_uuid, target_generation, updates=updates)

    if ctype == "CheckpointRequestCommand":
        checkpoint_now = bool(obj.get("checkpoint_now", True))
        label = str(obj.get("label", "control_plane_checkpoint") or "control_plane_checkpoint")
        return CheckpointRequestCommand(schema_version, command_uuid, target_generation, checkpoint_now=checkpoint_now, label=label)

    if ctype == "PlanAmendCommand":
        plan_id = str(obj.get("plan_id", "") or "")
        base_plan_version = int(obj.get("base_plan_version", 0))
        expectation_note = str(obj.get("expectation_note", "") or "")
        add_commands = obj.get("add_commands", []) or []
        supercede = obj.get("supercede_command_uuids", []) or []
        if not isinstance(add_commands, list):
            raise TypeError("add_commands must be a list")
        if not isinstance(supercede, list):
            raise TypeError("supercede_command_uuids must be a list")
        return PlanAmendCommand(
            schema_version,
            command_uuid,
            target_generation,
            plan_id=plan_id,
            base_plan_version=base_plan_version,
            expectation_note=expectation_note,
            add_commands=add_commands,
            supercede_command_uuids=[str(x) for x in supercede],
        )

    if ctype == "PlanCancelCommand":
        plan_id = str(obj.get("plan_id", "") or "")
        base_plan_version = int(obj.get("base_plan_version", 0))
        expectation_note = str(obj.get("expectation_note", "") or "")
        cancel = obj.get("cancel_command_uuids", []) or []
        if not isinstance(cancel, list):
            raise TypeError("cancel_command_uuids must be a list")
        return PlanCancelCommand(
            schema_version,
            command_uuid,
            target_generation,
            plan_id=plan_id,
            base_plan_version=base_plan_version,
            expectation_note=expectation_note,
            cancel_command_uuids=[str(x) for x in cancel],
        )

    if ctype == "TraitInjectionCommand":
        ti = obj.get("trait_injection", {})
        if not isinstance(ti, dict):
            raise TypeError("trait_injection must be a dict")
        return TraitInjectionCommand(schema_version, command_uuid, target_generation, trait_injection=dict(ti))

    raise ValueError(f"unknown command_type: {ctype!r}")


def _apply_dotpath(root: Any, path: str, value: Any) -> None:
    """Apply value to root at dot path like 'env.cfg.foo'.

    This is intentionally conservative:
    - Only supports attribute traversal plus dict key traversal.
    - Does not create intermediate objects.
    """
    parts = [p for p in str(path).split(".") if p]
    if not parts:
        return
    cur = root
    for p in parts[:-1]:
        if isinstance(cur, dict):
            if p not in cur:
                raise KeyError(f"dotpath missing dict key: {p}")
            cur = cur[p]
        else:
            if not hasattr(cur, p):
                raise AttributeError(f"dotpath missing attr: {p}")
            cur = getattr(cur, p)
    leaf = parts[-1]
    if isinstance(cur, dict):
        if leaf not in cur:
            raise KeyError(f"dotpath missing dict key: {leaf}")
        cur[leaf] = value
    else:
        if not hasattr(cur, leaf):
            raise AttributeError(f"dotpath missing attr: {leaf}")
        setattr(cur, leaf, value)
