from __future__ import annotations
"""simulation/control_plane_pkg/commands.py

Phase 2 command schemas (minimum viable set).

This module is intentionally small and strict:
- Commands are pure data + a deterministic apply() hook.
- No timestamps. No ordering fields derived from wall clock.
- command_uuid is provided by the submitter (or generated by tooling) and is the idempotency key.

Command Types
-------------
- PressureUpdateCommand: deterministic patch of pressure-related knobs (config/env multipliers).
- CheckpointRequestCommand: request a checkpoint (picked up by runner).
- PlanAmendCommand: amend a plan (create a new InterventionPlan version).
- PlanCancelCommand: cancel scheduled commands in a plan (also new version).
- TraitInjectionCommand: Phase 5B, inject genome trait alleles via ControlPlane.

All commands share a canonical payload used for payload_hash (CMD-WAL-02).
"""

from dataclasses import dataclass
from typing import Any, Dict, List, Optional, Protocol, runtime_checkable

import uuid as _uuid

from simulation.trait_injection_pkg.cost_model import trait_injection_cost_model
from simulation.trait_injection_pkg.schema_v2 import normalize_duration_generations


@runtime_checkable
class AppliesToSim(Protocol):
    def apply_to_sim(self, sim: Any) -> None:
        ...


@dataclass(frozen=True)
class CommandBase:
    """Base class for all ControlPlane commands."""

    schema_version: str
    command_uuid: str
    target_generation: int

    def payload_dict(self) -> Dict[str, Any]:
        """Return the canonical payload dict (determinism-critical)."""
        raise NotImplementedError

    def apply_to_sim(self, sim: Any) -> None:
        """Apply the command to the simulation object at SafeBoundary."""
        # Default is no-op.
        return


@dataclass(frozen=True)
class PressureUpdateCommand(CommandBase):
    """Update one or more pressure knobs via deterministic dot-path assignment."""

    # Example:
    # updates = [{"path": "env.cfg.tier4_juvenile_hazard_multiplier", "value": 1.5}]
    updates: List[Dict[str, Any]]

    def payload_dict(self) -> Dict[str, Any]:
        return {
            "schema_version": self.schema_version,
            "command_type": "PressureUpdateCommand",
            "command_uuid": self.command_uuid,
            "target_generation": int(self.target_generation),
            "updates": self.updates,
        }

    def apply_to_sim(self, sim: Any) -> None:
        # Best-effort. We do NOT invent a new env architecture here.
        # We deterministically set attributes using a dotted path.
        for upd in self.updates:
            if not isinstance(upd, dict):
                continue
            path = str(upd.get("path", "") or "")
            if not path:
                continue
            value = upd.get("value", None)
            _apply_dotpath(sim, path, value)


@dataclass(frozen=True)
class CheckpointRequestCommand(CommandBase):
    """Request a checkpoint at or after this SafeBoundary."""

    # When True, runner should checkpoint immediately at this boundary.
    checkpoint_now: bool = True
    label: str = "control_plane_checkpoint"

    def payload_dict(self) -> Dict[str, Any]:
        return {
            "schema_version": self.schema_version,
            "command_type": "CheckpointRequestCommand",
            "command_uuid": self.command_uuid,
            "target_generation": int(self.target_generation),
            "checkpoint_now": bool(self.checkpoint_now),
            "label": str(self.label or ""),
        }

    def apply_to_sim(self, sim: Any) -> None:
        # Runner loop should pick this up after process_pending returns.
        try:
            setattr(sim, "_control_plane_checkpoint_now", bool(self.checkpoint_now))
            setattr(sim, "_control_plane_checkpoint_label", str(self.label or "control_plane_checkpoint"))
        except Exception:
            pass


@dataclass(frozen=True)
class PlanAmendCommand(CommandBase):
    """Create a new plan version (N+1) from an existing plan version N.

    - expectation_note is REQUIRED for any version increment.
    - Adds and/or supercedes future commands.
    """

    plan_id: str
    base_plan_version: int
    expectation_note: str
    add_commands: List[Dict[str, Any]]
    supercede_command_uuids: List[str]

    def payload_dict(self) -> Dict[str, Any]:
        return {
            "schema_version": self.schema_version,
            "command_type": "PlanAmendCommand",
            "command_uuid": self.command_uuid,
            "target_generation": int(self.target_generation),
            "plan_id": self.plan_id,
            "base_plan_version": int(self.base_plan_version),
            "expectation_note": str(self.expectation_note or ""),
            "add_commands": self.add_commands,
            "supercede_command_uuids": list(self.supercede_command_uuids),
        }


@dataclass(frozen=True)
class PlanCancelCommand(CommandBase):
    """Cancel future commands by creating a new plan version (N+1)."""

