from __future__ import annotations

"""
simulation/replay_engine.py

Phase 3: Replay Engine (exact-hash replay).

Purpose
-------
Given:
- a run_dir containing Phase 2 ControlPlane artifacts (wal/, events/)
- a Checkpoint Bundle v2 produced during the run
- a SafeBoundary hash log (generated by Phase 3 runner integration)

This module:
- loads the checkpoint bundle
- resumes the simulation from that SafeBoundary
- replays forward using the normal runner loop path
- compares determinism-critical hashes at every SafeBoundary
- fails fast with a clear mismatch category

Mismatch categories (TSD v3.1)
------------------------------
- RNG_DIVERGENCE
- POPULATION_MISMATCH
- EVENT_ORDER_MISMATCH
- METRIC_MISMATCH
- SCHEMA_MISMATCH

Notes
-----
- Minimal-change: we do not implement a parallel "replay-only" simulation path.
  Replay uses the normal runner loop and ControlPlane.process_pending().
- This engine relies on the SafeBoundary hash log file written by the runner
  when `SimConfig.safeboundary_hash_log_enable=True`.
"""

import os
from dataclasses import dataclass
from typing import Any, Dict, Optional

from simulation.checkpoint_bundle_v2 import (
    checkpoint_bundle_v2_load,
    checkpoint_bundle_v2_apply,
    CheckpointBundleError,
    CheckpointStrictError,
)
from simulation.safeboundary_hash_log import (
    read_safeboundary_hash_log,
    compute_safeboundary_hashes,
)


@dataclass(frozen=True)
class ReplayMismatch(RuntimeError):
    category: str
    generation_index: int
    expected: Dict[str, Any]
    got: Dict[str, Any]

    def __str__(self) -> str:
        return f"[{self.category}] gen={self.generation_index} expected={self.expected} got={self.got}"


def replay_from_checkpoint_v2(
    sim: Any,
    *,
    bundle_dir: str,
    run_dir: str,
    end_generation: int,
    strict: bool = True,
) -> None:
    """Replay deterministically from a checkpoint bundle until end_generation.

    Parameters
    ----------
    sim:
        A SimulationRunner instance, already constructed with the same configs.
        The function will apply checkpoint state to it.
    bundle_dir:
        Path to the checkpoint bundle v2 directory.
    run_dir:
        Run directory containing events/ and wal/ (Phase 2 artifacts).
    end_generation:
        Absolute generation index (exclusive) to run until.
    strict:
        Enforce strict validation (commit mismatch rejection if enabled by bundle).

    Raises
    ------
    ReplayMismatch on any exact hash mismatch.
    """
    payload = checkpoint_bundle_v2_load(
        bundle_dir,
        strict=bool(strict),
        expected_commit_hash=getattr(sim, "git_commit", None),
    )
    meta = payload.get("metadata", {}) or {}
    start_gen = int(meta.get("generation_index", 0) or 0)

    # Strict replay requires a hash log.
    log_path = os.path.join(str(run_dir), "hashes", "safeboundary_hashes.jsonl")
    ref = read_safeboundary_hash_log(log_path)
    if strict and not ref:
        raise CheckpointStrictError(f"strict replay requires safeboundary hash log: {log_path}")

    # Apply checkpoint state
    checkpoint_bundle_v2_apply(sim, payload, restore_rng=True)

    # Install replay hook into runner loop (called at SafeBoundary next_gen).
    def _hook(next_gen: int) -> None:
        got = compute_safeboundary_hashes(sim)
        exp = ref.get(int(next_gen))
        if exp is None:
            if strict:
                raise ReplayMismatch("SCHEMA_MISMATCH", int(next_gen), {"missing_ref": True}, got)
            return

        # Compare exact fields
        for k, cat in [
            ("rng_snapshot_hash", "RNG_DIVERGENCE"),
            ("population_hash", "POPULATION_MISMATCH"),
            ("event_log_hash", "EVENT_ORDER_MISMATCH"),
            ("wal_hash", "EVENT_ORDER_MISMATCH"),
        ]:
            if str(exp.get(k, "")) != str(got.get(k, "")):
                raise ReplayMismatch(cat, int(next_gen), {"field": k, "value": exp.get(k)}, {"field": k, "value": got.get(k)})

        # Boundary metrics hash (REPLAY-ORDER-01)
        if str(exp.get("boundary_metrics_hash", "")) != str(got.get("boundary_metrics_hash", "")):
            raise ReplayMismatch("METRIC_MISMATCH", int(next_gen), {"boundary_metrics_hash": exp.get("boundary_metrics_hash")}, {"boundary_metrics_hash": got.get("boundary_metrics_hash")})

        # Legacy metrics hash (optional)
        if ("metrics_hash" in exp) or ("metrics_hash" in got):
            if str(exp.get("metrics_hash", "")) != str(got.get("metrics_hash", "")):
                raise ReplayMismatch("METRIC_MISMATCH", int(next_gen), {"metrics_hash": exp.get("metrics_hash")}, {"metrics_hash": got.get("metrics_hash")})

    setattr(sim, "_replay_hook", _hook)

    # Run using normal loop path. We must skip init to avoid overwriting restored state.
    # Important: we run from start_gen to end_generation using runner's `generations` as delta.
    sim.sim_cfg.generations = int(end_generation) - int(start_gen)
    sim.run(start_gen=int(start_gen), skip_init=True)
